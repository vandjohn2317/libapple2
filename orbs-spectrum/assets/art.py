# Tone remaps per tile for the Spectrum.
SPEC_TONES = {"WALL": {1: 0, 2: 3, 3: 3}, "WALL_F": {1: 0, 2: 1, 3: 3},
              "PILLAR": {1: 1, 2: 3, 3: 3}}


def parse(txt, w, name="art"):
    rows = txt.strip("\n").split("\n")
    out = []
    for i, r in enumerate(rows):
        r = r.replace(" ", "2")
        r = (r + "." * w)[:w] if name == "BOSS" else r
        if len(r) != w:
            raise SystemExit(f"{name} row {i} has width {len(r)} not {w}: {r!r}")
        out.append([0 if c == "." else int(c) for c in r])
    while name == "BOSS" and len(out) < 32:
        out.append([0] * w)
    return out
